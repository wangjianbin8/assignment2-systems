import torch


# ==============================
# Case 1:
# FP32 tensor 做累加
# ==============================

s = torch.tensor(
    0,
    dtype=torch.float32
)


for i in range(1000):

    # 每次加入 0.01
    s += torch.tensor(
        0.01,
        dtype=torch.float32
    )


print("FP32 accumulation:")
print(s)



# ==============================
# Case 2:
# FP16 tensor 做累加
# ==============================

s = torch.tensor(
    0,
    dtype=torch.float16
)


for i in range(1000):

    s += torch.tensor(
        0.01,
        dtype=torch.float16
    )


print("FP16 accumulation:")
print(s)



# ==============================
# Case 3:
# FP32 accumulator
# 但是输入是 FP16
# ==============================

s = torch.tensor(
    0,
    dtype=torch.float32
)


for i in range(1000):

    x = torch.tensor(
        0.01,
        dtype=torch.float16
    )


    # 关键：
    # 加之前转换回 FP32

    s += x.type(torch.float32)


print("FP16 input + FP32 accumulation:")
print(s)

